// Persistência em PostgreSQL com a MESMA interface síncrona do Store do SQLite (store.js): mesmos
// métodos, mesmos formatos de retorno, tx(fn) com BEGIN/COMMIT/ROLLBACK. A lógica do jogo não sabe qual
// banco está usando. As chamadas passam pela ponte síncrona (pg-bridge.js -> pg-worker.js), que tem uma
// conexão dedicada; por isso a transação de tx(fn) é de verdade (todos os comandos na mesma conexão).
//
// Tradução em relação ao SQLite:
// - parâmetros $1..$n; RETURNING id em vez de lastInsertRowid; ON CONFLICT DO NOTHING em vez de
//   INSERT OR IGNORE; sem PRAGMA (chaves estrangeiras valem sempre; lock_timeout de 3 s faz o papel do
//   busy_timeout);
// - INTEGER do SQLite (64 bits) -> BIGINT (lido como número); REAL -> DOUBLE PRECISION; TEXT -> TEXT;
// - nomes de conta, personagem e clã, sigla do clã e e-mail sem diferença de maiúsculas: a função
//   nocase(texto) do esquema troca só A-Z por a-z (exatamente o COLLATE NOCASE do SQLite, que não mexe
//   em letras fora do ASCII, e sem depender do locale do banco, ao contrário de lower()); índices únicos
//   em nocase(...) e buscas por nocase(coluna) = nocase($1); ordem por nocase(coluna) COLLATE "C";
// - ordem: onde o SQLite devolve numa ordem implícita (missões pelo índice da chave), a consulta tem
//   ORDER BY explícito (COLLATE "C" = comparação binária, como no SQLite);
// - account_codes ganha a coluna rid (identidade) no lugar do rowid implícito do SQLite.
//
// Toda migração nova precisa ser escrita para os dois bancos: MIGRATIONS (store.js) e PG_MIGRATIONS
// (aqui), com a mesma versão e o mesmo nome — o teste db.test.js confere.
