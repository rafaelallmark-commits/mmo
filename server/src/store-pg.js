const SCHEMA_RE = /^[A-Za-z_][A-Za-z0-9_]{0,62}$/;
const LOCK_NS = 0x435a4442; // 'CZDB': trava consultiva das migrações (com o hash do esquema)
const ident = (s) => `"${String(s).replace(/"/g, '""')}"`;

export const isPostgresUrl = (s) => typeof s === 'string' && /^postgres(ql)?:\/\//i.test(s);

// postgres://usuario:senha@host:5432/banco?schema=cinzas  (schema é nosso; o resto vai para o 'pg')
export function parsePgUrl(url) {
  const u = new URL(url);
  const schema = u.searchParams.get('schema');
  u.searchParams.delete('schema');
  const user = decodeURIComponent(u.username);
  const host = u.searchParams.get('host') || u.hostname || 'localhost';
  const port = u.searchParams.get('port') || u.port || '5432';
  const db = decodeURIComponent(u.pathname.replace(/^\//, '')) || user;
  return { connectionString: u.toString(), schema: schema || null, label: `${user ? `${user}@` : ''}${host}:${port}/${db}`, database: db };
}

// "?" fora de aspas -> $1, $2, ... (aspas simples e duplas; '' dentro da string funciona)
export function questionToDollar(sql) {
  let n = 0, out = '', quote = null;
  for (const ch of sql) {
    if (quote) { out += ch; if (ch === quote) quote = null; continue; }
    if (ch === "'" || ch === '"') { quote = ch; out += ch; continue; }
    out += ch === '?' ? `$${++n}` : ch;
  }
  return out;
}

function lockKey(schema) {
  let h = 0x811c9dc5;
  for (let i = 0; i < schema.length; i++) { h ^= schema.charCodeAt(i); h = Math.imul(h, 0x01000193); }
  return h | 0;
}

