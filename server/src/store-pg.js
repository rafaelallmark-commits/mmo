// Senha num arquivo (segredo do Docker Compose, arquivo só do serviço): o conteúdo inteiro, sem as quebras
// de linha do fim (como o POSTGRES_PASSWORD_FILE da imagem oficial do PostgreSQL).
export function readPasswordFile(path) {
  let text;
  try { text = readFileSync(path, 'utf8'); } catch (e) { throw new Error(`não consegui ler a senha do banco em ${path} (CINZAS_DB_PASSWORD_FILE): ${e.code ?? e.message}`); }
  const pw = text.replace(/[\r\n]+$/, '');
  if (!pw) throw new Error(`o arquivo de senha do banco ${path} (CINZAS_DB_PASSWORD_FILE) está vazio`);
  return pw;
}

// postgres://usuario:senha@host:5432/banco?schema=cinzas  (schema é nosso; o resto vai para o 'pg')
// Sem senha na URL e com passwordFile (padrão: CINZAS_DB_PASSWORD_FILE), a senha vem do arquivo e entra
// na string de conexão (nunca no rótulo dos logs). Ela entra codificada (encodeURIComponent): o setter da
// URL não codifica "%", e o 'pg' (como o pg_dump) decodifica a senha da URL — "ab%41" viraria "abA".
export function parsePgUrl(url, { passwordFile = process.env.CINZAS_DB_PASSWORD_FILE } = {}) {
  const u = new URL(url);
  const schema = u.searchParams.get('schema');
  u.searchParams.delete('schema');
  if (!u.password && passwordFile) u.password = encodeURIComponent(readPasswordFile(passwordFile));
  const user = decodeURIComponent(u.username);
  const host = u.searchParams.get('host') || u.hostname || 'localhost';
  const port = u.searchParams.get('port') || u.port || '5432';
  const db = decodeURIComponent(u.pathname.replace(/^\//, '')) || user;
  return { connectionString: u.toString(), schema: schema || null, label: `${user ? `${user}@` : ''}${host}:${port}/${db}`, database: db };
}

// "?" fora de aspas -> $1, $2, ... (aspas simples e duplas; '' dentro da string funciona)
export function questionToDollar(sql) {
  let n = 0, out = '', quote = null;
  for (const ch of sql) {
    if (quote) { out += ch; if (ch === quote) quote = null; continue; }
    if (ch === "'" || ch === '"') { quote = ch; out += ch; continue; }
    out += ch === '?' ? `$${++n}` : ch;
  }
  return out;
}

