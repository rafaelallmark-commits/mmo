  saveCharacters(list) {
    if (!list.length) return;
    const byId = new Map();
    for (const c of list) byId.set(c.id, c); // repetido: vale o último, como no laço do SQLite
    const now = Date.now();
    const cols = Array.from({ length: 17 }, () => []);
    for (const c of byId.values()) charSaveValues(c, now).forEach((v, i) => cols[i].push(v));
    this.run(SAVE_CHARS, ...cols);
  }

